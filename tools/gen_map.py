#!/usr/bin/env python3
"""Writes docs/MAP.md: every source file with its size, purpose and declarations (with line numbers), so a change can start
from a grep of one small file instead of reading the code. `python3 tools/gen_map.py` rewrites it; `--check` fails if it is stale (CI)."""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "app/src/main"
OUT = ROOT / "docs/MAP.md"
DECL = re.compile(r"^(\s*)((?:(?:private|internal|public|protected|override|suspend|inline|data|enum|sealed|abstract|open|lateinit|const|operator|companion)\s+)*)(class|object|interface|fun|val|var)\s+(?:<[^>]+>\s*)?([\w.]+)(.*)$")

def first_doc(lines, i):
    """The first sentence of the comment right above line i, or ''."""
    j = i - 1
    while j >= 0 and lines[j].strip().startswith("@"): j -= 1
    if j < 0: return ""
    t = lines[j].strip()
    if t.startswith("//"): return t.lstrip("/ ").strip()
    if t.endswith("*/"):
        k = j
        while k >= 0 and "/**" not in lines[k]: k -= 1
        text = " ".join(l.strip().lstrip("/*").rstrip("*/").strip() for l in lines[max(k, 0):j + 1]).strip()
        return re.split(r"(?<=[.!?])\s", text)[0][:110]
    return ""

def describe(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    head = ""
    for i, l in enumerate(lines):
        if l.startswith(("class ", "object ", "data class ", "enum class ", "interface ")) or re.match(r"^(abstract |open )?class ", l):
            head = first_doc(lines, i); break
    out = []
    for i, l in enumerate(lines):
        m = DECL.match(l)
        if not m: continue
        indent, mods, kind, name, rest = len(m.group(1)), m.group(2), m.group(3), m.group(4), m.group(5)
        if indent > 4 or ("private" in mods and kind != "fun"): continue
        if kind in ("val", "var") and indent == 0 and not path.name.endswith("Prefs.kt"): continue
        if kind in ("val", "var") and indent == 4 and not path.name.endswith("Prefs.kt"): continue
        sig = (kind + " " + name + (re.match(r"\([^)]*\)?", rest.strip()).group(0) if kind == "fun" and rest.strip().startswith("(") else "")).strip()
        doc = first_doc(lines, i)
        out.append(f"  {i + 1:>4} {'  ' if indent else ''}{sig[:80]}" + (f"  - {doc}" if doc else ""))
    return len(lines), head, out

def build():
    parts = ["# Code map (generated by tools/gen_map.py: do not edit by hand)\n",
             "Find a symbol with grep on this file, then read only that file around the line number. Task-to-file hints are in docs/INDEX.md.\n"]
    for path in sorted((SRC / "java").rglob("*.kt"), key=lambda p: p.as_posix()):
        n, head, decls = describe(path)
        rel = path.relative_to(SRC / "java/tv/myliststv/launcher").as_posix()
        parts.append(f"\n## {rel} ({n} lines){' - ' + head if head else ''}")
        parts += decls
    parts.append("\n## Resources and manifest")
    for p in sorted((SRC / "res").rglob("*.xml"), key=lambda p: p.as_posix()): parts.append(f"  {p.relative_to(SRC).as_posix()}")
    comps = re.findall(r'<(activity|service)[^>]*android:name="([^"]+)"', (SRC / "AndroidManifest.xml").read_text(encoding="utf-8"))
    parts.append("  manifest components: " + ", ".join(f"{k} {n}" for k, n in comps))
    return "\n".join(parts) + "\n"

if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("docs/MAP.md is out of date: run python3 tools/gen_map.py and commit it"); sys.exit(1)
        print("docs/MAP.md is up to date")
    else:
        OUT.write_text(text, encoding="utf-8"); print(f"wrote {OUT} ({len(text)} bytes)")
